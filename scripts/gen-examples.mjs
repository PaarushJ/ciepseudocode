/* Builds web/examples.js from the .cps programs in examples/.
   Run automatically as part of the Vercel build. */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const TITLES = {
  'input_output'   : 'Input and output',
  'if_statements'  : 'IF statements',
  'case_statements': 'CASE statements',
  'for_loops'      : 'FOR loops',
  'while_loops'    : 'WHILE loops',
  'procedures'     : 'Procedures',
  'functions'      : 'Functions',
  '1d_arrays'      : '1-D arrays',
  '2d_arrays'      : '2-D arrays',
  'file_handling'  : 'File handling',
  'dates'          : 'Dates',
  'bubble_sort'    : 'Bubble sort',
  'linear_search'  : 'Linear search',
};
const ORDER = ['input_output','if_statements','case_statements','for_loops','while_loops',
               'procedures','functions','1d_arrays','2d_arrays','dates','file_handling'];

const title = (s) => TITLES[s] || s.replace(/[_-]/g, ' ').replace(/^\w/, c => c.toUpperCase());

function collect(dir){
  return readdirSync(dir)
    .filter(f => f.endsWith('.cps'))
    .map(f => {
      const stem = f.replace(/\.cps$/, '');
      return { stem, file: f, title: title(stem), code: readFileSync(join(dir, f), 'utf8') };
    });
}

const basics = collect('examples')
  .sort((a,b) => {
    const ia = ORDER.indexOf(a.stem), ib = ORDER.indexOf(b.stem);
    return (ia === -1 ? 99 : ia) - (ib === -1 ? 99 : ib);
  });
const algos = collect('examples/algorithms');

const groups = [
  { group: 'Language basics', items: basics },
  { group: 'Algorithms',      items: algos  },
].filter(g => g.items.length);

const banner =
`/* AUTO-GENERATED by scripts/gen-examples.mjs — do not edit by hand.
   Source programs: examples/ in this repository (GPL-3.0, Faisal Fakih). */\n`;

writeFileSync('web/examples.js',
  banner + 'export const EXAMPLES = ' + JSON.stringify(groups, null, 2) + ';\n');

console.log(`examples.js: ${groups.reduce((n,g) => n + g.items.length, 0)} programs in ${groups.length} groups`);
